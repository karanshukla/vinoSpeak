"""The Kokoro model: where it lives, how it is downloaded, and how it is checked.

The download is pinned to one Hugging Face commit and every file is checked
against the sha256 in model_pins.json (generated by scripts/update_pins.py).
"""

from __future__ import annotations

import fcntl
import hashlib
import json
import os
import shutil
from collections.abc import Iterator
from contextlib import contextmanager, nullcontext, suppress
from dataclasses import dataclass
from pathlib import Path

PINS_PATH = Path(__file__).resolve().parent / "model_pins.json"

MODEL_ID = "OpenVINO/Kokoro-82M-int8-ov"
# What the pipeline cannot start without, and all a --model-dir you supply
# needs (pinned by `test_model.py::test_a_directory_you_supply_is_used_as_given`,
# `test_model.py::test_an_empty_directory_you_supply_still_gets_the_pinned_model`).
MODEL_FILES = (
    "openvino_model.xml",
    "openvino_model.bin",
    "config.json",
    "voices/af_heart.bin",
    "data/us_gold.json",
)

_HASH_CHUNK_BYTES = 1 << 20


class ModelIntegrityError(RuntimeError):
    pass


class ModelBusyError(RuntimeError):
    """The model is being downloaded, so it can't be deleted now."""


@dataclass(frozen=True)
class Pins:
    model_id: str
    revision: str
    files: dict[str, dict[str, int | str]]


def load_pins(path: Path = PINS_PATH) -> Pins:
    record = json.loads(path.read_text(encoding="utf-8"))
    return Pins(record["model_id"], record["revision"], record["files"])


def cache_dir() -> Path:
    """vinoSpeak's cache: the model and OpenVINO's compiled copy, nothing else."""
    cache = Path(os.environ.get("XDG_CACHE_HOME") or Path.home() / ".cache")
    return cache / "vinospeak"


def default_model_dir() -> Path:
    return cache_dir() / "kokoro-82m-int8-ov"


def compile_cache_dir() -> Path:
    """Where OpenVINO keeps the compiled model between processes."""
    return cache_dir() / "ov-cache"


# Shared while the default model downloads, exclusive while it is deleted
# (pinned by `test_model.py::test_delete_cached_refuses_during_a_download`).
_LOCK = ".lock"


@contextmanager
def _locked(operation: int) -> Iterator[None]:
    cache_dir().mkdir(parents=True, exist_ok=True)
    with (cache_dir() / _LOCK).open("a") as handle:
        fcntl.flock(handle, operation)
        yield


def disk_usage(path: Path) -> int:
    """Bytes in the files under path, not following links."""
    return sum(f.lstat().st_size for f in path.rglob("*") if f.is_file() and not f.is_symlink())


def cached() -> dict[Path, int]:
    """The downloaded model and the compiled cache, with their sizes, where they exist."""
    return {d: disk_usage(d) for d in (default_model_dir(), compile_cache_dir()) if d.is_dir()}


def delete_cached() -> int:
    """Delete the downloaded model and the compiled cache; the bytes freed.

    A --model-dir is never touched, nor anything else in the cache directory
    (pinned by `test_model.py::test_delete_cached_keeps_what_isnt_ours`). The
    next run downloads the model again.
    """
    if not cache_dir().is_dir():
        return 0
    try:
        with _locked(fcntl.LOCK_EX | fcntl.LOCK_NB):
            found = cached()
            for directory in found:
                shutil.rmtree(directory)
            (cache_dir() / _LOCK).unlink(missing_ok=True)
    except BlockingIOError:
        raise ModelBusyError(
            "The model is downloading; delete it once the download has finished."
        ) from None
    with suppress(OSError):
        cache_dir().rmdir()
    return sum(found.values())


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        while chunk := handle.read(_HASH_CHUNK_BYTES):
            digest.update(chunk)
    return digest.hexdigest()


# Written once every file has matched its pinned sha256; without it a run
# hashes the whole model instead of comparing sizes (pinned by
# `test_model.py::test_an_unstamped_model_is_hashed_in_full`,
# `test_model.py::test_a_verified_model_is_stamped_then_size_checked`).
STAMP = ".vinospeak-verified"


def _stamp_value(pins: Pins) -> str:
    """Changes with the revision or any pin, so new pins re-hash the model."""
    record = json.dumps([pins.model_id, pins.revision, pins.files], sort_keys=True)
    return hashlib.sha256(record.encode()).hexdigest()


def _is_stamped(model_dir: Path, pins: Pins) -> bool:
    try:
        return (model_dir / STAMP).read_text(encoding="utf-8").strip() == _stamp_value(pins)
    except OSError:
        return False


def _stamp(model_dir: Path, pins: Pins) -> None:
    (model_dir / STAMP).write_text(_stamp_value(pins) + "\n", encoding="utf-8")


def model_is_ready(model_dir: Path) -> bool:
    return all((model_dir / filename).is_file() for filename in MODEL_FILES)


def _mismatches(path: Path, pin: dict[str, int | str]) -> bool:
    """True when the file at path is not what pin describes."""
    return path.stat().st_size != pin["size"] or sha256_file(path) != pin["sha256"]


def verify(model_dir: Path, pins: Pins | None = None, *, full: bool = True) -> list[str]:
    """Problems with the model in model_dir; empty means it is the pinned model.

    full=False compares sizes only (cheap enough for every run); full=True also
    hashes every file (~160 MB).
    """
    pins = pins or load_pins()
    problems = []
    for name, pin in pins.files.items():
        path = model_dir / name
        if not path.is_file():
            problems.append(f"{name} is missing")
        elif path.stat().st_size != pin["size"]:
            problems.append(f"{name} has {path.stat().st_size} bytes, pinned {pin['size']}")
        elif full and sha256_file(path) != pin["sha256"]:
            problems.append(f"{name} does not match its pinned sha256")
    return problems


def _redownload_hint(model_dir: Path) -> str:
    if model_dir == default_model_dir():
        return "Run vinospeak --delete-model to download it again."
    return "Delete the directory to download it again."


def _check_against_pins(model_dir: Path, pins: Pins) -> None:
    """Sizes only for a stamped model, every hash for one not yet stamped."""
    stamped = _is_stamped(model_dir, pins)
    problems = verify(model_dir, pins, full=not stamped)
    if problems:
        raise ModelIntegrityError(
            f"The model in {model_dir} is not the pinned revision ({problems[0]}). "
            + _redownload_hint(model_dir)
        )
    if not stamped:
        _stamp(model_dir, pins)


def _remove_mismatched(model_dir: Path, pins: Pins) -> None:
    for name, pin in pins.files.items():
        path = model_dir / name
        if path.is_file() and _mismatches(path, pin):
            path.unlink()


def _download(model_dir: Path, pins: Pins) -> None:
    try:
        from huggingface_hub import snapshot_download
    except ImportError as error:
        raise RuntimeError("huggingface-hub is required to download the Kokoro model.") from error

    with _locked(fcntl.LOCK_SH) if model_dir == default_model_dir() else nullcontext():
        model_dir.mkdir(parents=True, exist_ok=True)
        snapshot_download(
            repo_id=pins.model_id,
            revision=pins.revision,
            local_dir=str(model_dir),
            allow_patterns=list(pins.files),
        )
    problems = verify(model_dir, pins)
    if problems:
        _remove_mismatched(model_dir, pins)
        raise ModelIntegrityError(
            f"The download in {model_dir} failed verification: {'; '.join(problems[:3])}. "
            "The files that failed were removed; run again to download them again."
        )
    _stamp(model_dir, pins)


def ensure_model(model_dir: Path, *, trusted: bool = False) -> Path:
    """Return a usable model directory, downloading the pinned model if needed.

    trusted=True is a directory the caller supplied: it only has to hold
    MODEL_FILES, and its contents are not compared with the pins.
    """
    present = model_is_ready(model_dir)
    if trusted and present:
        return model_dir
    pins = load_pins()
    if present:
        _check_against_pins(model_dir, pins)
    else:
        _download(model_dir, pins)
    return model_dir
