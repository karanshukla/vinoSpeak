"""The Kokoro model: where it lives, how it is downloaded, and how it is checked.

The download is pinned to one Hugging Face commit and every file is checked
against the sha256 in model_pins.json (generated by scripts/update_pins.py).
"""

from __future__ import annotations

import hashlib
import json
import os
from dataclasses import dataclass
from pathlib import Path

PINS_PATH = Path(__file__).resolve().parent / "model_pins.json"

MODEL_ID = "OpenVINO/Kokoro-82M-int8-ov"
# What the pipeline cannot start without; a --model-dir you supply only needs these.
MODEL_FILES = (
    "openvino_model.xml",
    "openvino_model.bin",
    "config.json",
    "voices/af_heart.bin",
    "data/us_gold.json",
)

_CHUNK = 1 << 20


class ModelIntegrityError(RuntimeError):
    pass


@dataclass(frozen=True)
class Pins:
    model_id: str
    revision: str
    files: dict[str, dict[str, int | str]]


def load_pins(path: Path = PINS_PATH) -> Pins:
    record = json.loads(path.read_text(encoding="utf-8"))
    return Pins(record["model_id"], record["revision"], record["files"])


def default_model_dir() -> Path:
    cache = Path(os.environ.get("XDG_CACHE_HOME") or Path.home() / ".cache")
    return cache / "vinospeak" / "kokoro-82m-int8-ov"


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        while chunk := handle.read(_CHUNK):
            digest.update(chunk)
    return digest.hexdigest()


def model_is_ready(model_dir: Path) -> bool:
    return all((model_dir / filename).is_file() for filename in MODEL_FILES)


def verify(model_dir: Path, pins: Pins | None = None, *, full: bool = True) -> list[str]:
    """Problems with the model in model_dir; empty means it is the pinned model.

    full=False compares sizes only (cheap enough for every run); full=True also
    hashes every file (~160 MB).
    """
    pins = pins or load_pins()
    problems = []
    for name, pin in pins.files.items():
        path = model_dir / name
        if not path.is_file():
            problems.append(f"{name} is missing")
        elif path.stat().st_size != pin["size"]:
            problems.append(f"{name} has {path.stat().st_size} bytes, pinned {pin['size']}")
        elif full and sha256_file(path) != pin["sha256"]:
            problems.append(f"{name} does not match its pinned sha256")
    return problems


def ensure_model(model_dir: Path, *, trusted: bool = False) -> Path:
    """Return a usable model directory, downloading the pinned model if needed.

    trusted=True is a directory the caller supplied: it only has to hold
    MODEL_FILES, and its contents are not compared with the pins.
    """
    if trusted and model_is_ready(model_dir):
        return model_dir

    pins = load_pins()
    if not trusted and model_is_ready(model_dir):
        problems = verify(model_dir, pins, full=False)
        if problems:
            raise ModelIntegrityError(
                f"The model in {model_dir} is not the pinned revision ({problems[0]}). "
                "Delete the directory to download it again."
            )
        return model_dir

    try:
        from huggingface_hub import snapshot_download
    except ImportError as error:
        raise RuntimeError("huggingface-hub is required to download the Kokoro model.") from error

    model_dir.mkdir(parents=True, exist_ok=True)
    snapshot_download(
        repo_id=pins.model_id,
        revision=pins.revision,
        local_dir=str(model_dir),
        allow_patterns=list(pins.files),
    )
    problems = verify(model_dir, pins)
    if problems:
        raise ModelIntegrityError(
            f"The download in {model_dir} failed verification: {'; '.join(problems[:3])}. "
            "Delete the directory and try again."
        )
    return model_dir
